#pragma once

//===========================================================
// カメラからロックオンできる対象の共通機能
//===========================================================
class ILockOnTarget
{
public:

	//===========================================================
	// コンストラクタ・デストラクタ
	//===========================================================
	ILockOnTarget()				= default;
	virtual ~ILockOnTarget()	= default;

	//===========================================================
	// 公開関数群
	//===========================================================
	// 現在ロックオンできる状態か
	virtual bool CanLockOn() const = 0;

	// カメラが狙う位置を返す
	virtual Math::Vector3 GetLockOnPosition() const = 0;
	// ロックオンマーカーを表示する位置を返す
	// 個別指定がなければ、カメラの注視位置と同じ場所を使う
	virtual Math::Vector3 GetLockOnMarkerPosition() const
	{
		return GetLockOnPosition();
	}
};