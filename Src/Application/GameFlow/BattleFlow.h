#pragma once

class Enemy;
class Player;

//===========================================================
// 戦闘全体が取り得る進行状態
//===========================================================
enum class BattleState
{
	Playing,
	Cleared,
	GameOver
};

//===========================================================
// PlayerとEnemyを監視し、戦闘の終了状態を決定する
//===========================================================
class BattleFlow : public KdGameObject
{
public:

	//===========================================================
	// コンストラクタ・デストラクタ
	//===========================================================
	BattleFlow() = default;
	~BattleFlow()	override = default;

	//===========================================================
	// 基本ライフサイクル
	//===========================================================
	void Update() override;

	//===========================================================
	// 公開関数
	//===========================================================
	void SetPlayer(const std::shared_ptr<Player>& player)
	{
		m_wpPlayer = player;
	}

	void RegisterEnemy(const std::shared_ptr<Enemy>& enemy);

	BattleState GetState() const
	{
		return m_state;
	}

private:

	//===========================================================
	// 内部処理
	//===========================================================
	void ChangeState(BattleState nextState);

	//===========================================================
	// 参照するオブジェクト
	//===========================================================
	std::weak_ptr<Player>				m_wpPlayer;
	std::vector<std::weak_ptr<Enemy>>	m_wpEnemies;

	//===========================================================
	// 状態値
	//===========================================================
	BattleState m_state = BattleState::Playing;
};