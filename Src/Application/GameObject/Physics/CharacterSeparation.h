#pragma once

//===========================================================
// 登録されたキャラクター同士の重なりを解消する
//===========================================================
class CharacterSeparation : public KdGameObject
{
public:

	//===========================================================
	// コンストラクタ・デストラクタ
	//===========================================================
	CharacterSeparation()				= default;
	~CharacterSeparation()	override	= default;

	//===========================================================
	// 基本ライフサイクル
	//===========================================================
	// 全キャラクターの移動後に重なりを解消する
	void PostUpdate() override;

	//===========================================================
	// 公開関数
	//===========================================================
	void RegisterBody(
		const std::shared_ptr<KdGameObject>& object,
		float radius,
		float height
	);

private:

	// 押し戻し対象と円柱サイズをひとまとめにする
	struct BodyEntry
	{
		std::weak_ptr<KdGameObject>	object;
		float						radius = 0.5f;
		float						height = 1.8f;
	};

	//===========================================================
	// 登録されたキャラクター
	//===========================================================
	std::vector<BodyEntry> m_bodies;
};