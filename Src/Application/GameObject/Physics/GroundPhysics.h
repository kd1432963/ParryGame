#pragma once

//===========================================================
// 重力と地面への接地を担当する共通クラス
//===========================================================
class GroundPhysics
{
public:

	//===========================================================
	// コンストラクタ・デストラクタ
	//===========================================================
	GroundPhysics();
	~GroundPhysics();

	//===========================================================
	// 公開関数
	//===========================================================
	void Update(
		KdGameObject&	gameObject,
		float			deltaTime,
		float			footOffsetY);

	bool IsGround() const { return m_isGrounded; }

private:

	//===========================================================
	// 状態値
	//===========================================================
	float	m_verticalVelocity	= 0.0f;
	bool	m_isGrounded		= false;
};
