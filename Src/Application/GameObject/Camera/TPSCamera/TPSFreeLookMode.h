#pragma once

//===========================================================
// 通常TPS時のマウスによるカメラ回転を担当する
//===========================================================
class TPSFreeLookMode
{
public:

	//===========================================================
	// コンストラクタ・デストラクタ
	//===========================================================
	TPSFreeLookMode()	= default;
	~TPSFreeLookMode() = default;

	//===========================================================
	// 公開関数群
	//===========================================================
	// マウス移動量からカメラ角度を更新する
	void Update(Math::Vector3& cameraAngle);

	// 切り替え直後のマウス移動を無視する
	void ResetInput();

private:

	//===========================================================
	// 状態値
	//===========================================================
	bool m_isMouseInputReady = false;
};